"""Special-column probe: which CLB column a region loses by covering a special
(site-less) column.

    python tools/probe_specials.py model.json xc7z020clg400-1 > probe_specials.tcl
    vivado -mode batch -log probe_specials.log -source probe_specials.tcl
    python tools/build_device_model.py probe_geometry_out.txt model.json \\
        --specials probe_specials.log

A special column has interconnect tiles but no sites, so a site-range pblock
cannot own them.  Vivado then sees the special column's interconnect pair as
split between the reconfigurable pblock and static, and prohibits placement in
the pair's other column ([Constraints 18-993] / [18-996] / [18-992]).  Whether
that happens depends on the column: on xc7z020, covering x=33 costs CLB column
x=32 (100 SLICEL per clock-region row) and covering x=50 costs nothing --
measured on RFP's GA design and reproduced by this probe.

The probe needs no user design.  It synthesizes a one-cell design, marks the
cell reconfigurable, and for each special column places it in a pblock that
spans the column's interconnect pair and one pair on each side (pair-aligned,
so the pblock's own edges split nothing), then records every interconnect
column Vivado reports split, between PROBE_SPECIAL markers in the log.  The
placement itself may fail (a tiny design in a prohibited pblock); only the
messages before it matter.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

TINY = r"""module rp(input clk, input [3:0] a, output reg [3:0] y);
  always @(posedge clk) y <= a ^ {a[2:0], a[3]};
endmodule
module top(input clk, input [3:0] a, output [3:0] y);
  (* keep_hierarchy = "yes" *) rp u (.clk(clk), .a(a), .y(y));
endmodule
"""


def probe_regions(dev):
    """special x -> (cols, row): the pair-aligned span around x's pair."""
    out = {}
    for x in dev.specials:
        lo = x if x % 2 == 0 else x - 1           # interconnect pair (lo, lo+1)
        cols = [c for c in range(lo - 2, lo + 4) if c in dev.columns]
        for r in range(dev.nrows):
            if all(dev.cell_ok(c, r) for c in cols):
                out[x] = (cols, r)
                break
    return out


def tcl(dev, part):
    from openflora import emit as _emit
    lines = ["# generated by tools/probe_specials.py",
             "set v [open probe_specials_tiny.v w]", "puts $v {%s}" % TINY, "close $v",
             "create_project -in_memory -part %s" % part,
             "read_verilog probe_specials_tiny.v",
             "synth_design -top top -part %s -flatten_hierarchy rebuilt" % part,
             "write_checkpoint -force probe_specials_tiny.dcp", "close_project"]
    for x, (cols, r) in sorted(probe_regions(dev).items()):
        ranges = " ".join(_emit.site_ranges(dev, cols, [r]))
        lines += ["open_checkpoint probe_specials_tiny.dcp",
                  "set_property HD.RECONFIGURABLE 1 [get_cells u]",
                  "create_pblock pb", "resize_pblock pb -add {%s}" % ranges,
                  "add_cells_to_pblock pb [get_cells u] -clear_locs",
                  "puts \"PROBE_SPECIAL %d row %d cols %s\"" % (x, r, ",".join(map(str, cols))),
                  "catch {place_design}",
                  "puts \"PROBE_SPECIAL_END %d\"" % x,
                  "close_design"]
    lines += ["exit"]
    return "\n".join(lines) + "\n"


def parse_log(path):
    """{special x: [SLICE site X numbers Vivado prohibited placement in]} from
    the probe's Vivado log: the [Constraints 18-993] detail line names the
    split interconnect tile and the slice sites of the column that loses its
    placement, e.g. "... interconnect tile INT_L_X32Y49  (SLICE_X49Y49
    SLICE_X48Y49)." (the tile may be the special's own interconnect, so the
    sites, not the tile, identify the lost column)."""
    out, cur = {}, None
    for ln in open(path, errors="replace"):
        if ln.startswith("PROBE_SPECIAL_END"):
            cur = None
        elif ln.startswith("PROBE_SPECIAL "):
            cur = int(ln.split()[1])
            out[cur] = []
        elif cur is not None and "contains interconnect tile INT_" in ln:
            for tok in ln.split("(", 1)[1].split(")")[0].split():
                if tok.startswith("SLICE_X"):
                    sx = int(tok[len("SLICE_X"):].split("Y")[0])
                    if sx not in out[cur]:
                        out[cur].append(sx)
    return out


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    sys.path.insert(0, os.path.join(HERE, "..", "src"))
    from openflora import device as _device
    with open(sys.argv[1]) as f:
        dev = _device.Device(json.load(f))
    sys.stdout.write(tcl(dev, sys.argv[2]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
